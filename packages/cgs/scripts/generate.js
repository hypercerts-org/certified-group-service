// Generates src/ for @hypercerts-org/cgs from the CGS-owned Lexicons under
// lexicons/app/ in the repository root, in lex's own layout: the package
// exports lex's NSID namespace tree (`app`), as in the @atproto/lex
// documentation. The deprecated proxy stubs under lexicons/com/atproto/repo/
// are intentionally excluded. Run with --check to fail when the committed
// output is stale.
import { execFileSync } from 'node:child_process'
import { existsSync } from 'node:fs'
import { mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const packageRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const repoRoot = path.resolve(packageRoot, '../..')
const cgsLexiconsRoot = path.join(repoRoot, 'lexicons/app')
const lexEntry = path.join(packageRoot, 'node_modules/@atproto/lex/bin/lex')
const header =
  '/*\n * THIS FILE WAS GENERATED BY scripts/generate.js WITH "@atproto/lex". DO NOT EDIT.\n */'
const lexHeader = '/*\n * THIS FILE WAS GENERATED BY "@atproto/lex". DO NOT EDIT.\n */'

/** @param {string} a @param {string} b */
const byCodeUnit = (a, b) => (a < b ? -1 : a > b ? 1 : 0)

/** @param {string} dir @returns {Promise<string[]>} paths relative to dir, POSIX separators */
async function listFiles(dir) {
  const entries = await readdir(dir, { recursive: true, withFileTypes: true }).catch(() => [])
  return entries
    .filter((entry) => entry.isFile() && !entry.name.startsWith('.'))
    .map((entry) =>
      path.relative(dir, path.join(entry.parentPath, entry.name)).split(path.sep).join('/'),
    )
    .sort(byCodeUnit)
}

/**
 * Loads all CGS-owned Lexicon JSON files under lexicons/app/.
 * @returns {Promise<Array<{ id: string; lexicon: unknown }>>}
 */
async function loadCgsLexicons() {
  const files = (await listFiles(cgsLexiconsRoot)).filter((file) => file.endsWith('.json'))
  if (files.length === 0) {
    throw new Error(`No Lexicon JSON files found under ${cgsLexiconsRoot}`)
  }
  return Promise.all(
    files.map(async (file) => {
      const fullPath = path.join(cgsLexiconsRoot, file)
      const lexicon = JSON.parse(await readFile(fullPath, 'utf8'))
      const id = /** @type {string} */ (lexicon.id)
      if (
        typeof id !== 'string' ||
        (!id.startsWith('app.certified.group.') && !id.startsWith('app.certified.groups.'))
      ) {
        throw new Error(`Unexpected Lexicon id "${id}" in ${fullPath}`)
      }
      return { id, lexicon }
    }),
  )
}

/** Order of the export forms lex writes in namespace modules. @param {string} line */
const exportRank = (line) =>
  line.startsWith('export * as ') ? 2 : line.startsWith('export {') ? 1 : 0

/**
 * Puts the lines lex writes in a fixed order. lex reads Lexicon files in the
 * order the file system lists them, which differs between machines, and that
 * order leaks into its output: the exports of namespace modules and the
 * imports of `.defs` modules.
 * @param {string} source
 * @param {boolean} isDefs
 */
function normalize(source, isDefs) {
  const lines = source.split('\n')
  if (isDefs) {
    const start = lines.findIndex((line) => line.startsWith('import * as '))
    if (start === -1) return source
    let end = start
    while (lines[end]?.startsWith('import * as ')) end++
    const imports = lines.slice(start, end).sort(byCodeUnit)
    return [...lines.slice(0, start), ...imports, ...lines.slice(end)].join('\n')
  }
  const first = lines.findIndex((line) => line.startsWith('export '))
  if (first === -1) return source
  const rest = lines.slice(first).filter((line) => line !== '')
  if (rest.some((line) => !line.startsWith('export '))) {
    throw new Error('Unexpected namespace module layout from @atproto/lex')
  }
  rest.sort((a, b) => exportRank(a) - exportRank(b) || byCodeUnit(a, b))
  return [...lines.slice(0, first), ...rest, ''].join('\n')
}

/**
 * Normalizes every generated module and replaces lex's banner with this
 * script's, since this script rewrites the files.
 * @param {string} lexiconsDir
 */
async function normalizeOutput(lexiconsDir) {
  for (const file of await listFiles(lexiconsDir)) {
    const absolute = path.join(lexiconsDir, file)
    const source = await readFile(absolute, 'utf8')
    if (!source.startsWith(lexHeader)) {
      throw new Error(`${file} does not start with the banner @atproto/lex writes`)
    }
    const normalized = normalize(header + source.slice(lexHeader.length), file.endsWith('.defs.ts'))
    if (normalized !== source) await writeFile(absolute, normalized)
  }
}

/** @param {string} srcDir */
async function writeIndex(srcDir) {
  const lines = [
    header,
    '',
    "// lex's NSID namespace tree for the Certified Group Service (CGS).",
    'export * from "./lexicons/index.js";',
  ]
  await writeFile(path.join(srcDir, 'index.ts'), `${lines.join('\n')}\n`)
}

/** @param {string} srcDir */
async function generate(srcDir) {
  if (!existsSync(lexEntry)) {
    throw new Error(`@atproto/lex is not installed at ${lexEntry}; run \`pnpm install\` first.`)
  }
  const lexicons = await loadCgsLexicons()
  const lexiconsDir = path.join(srcDir, 'lexicons')
  const inputDir = await mkdtemp(path.join(tmpdir(), 'hypercerts-cgs-lexicons-'))
  try {
    await Promise.all(
      lexicons.map(({ id, lexicon }) =>
        writeFile(path.join(inputDir, `${id}.json`), JSON.stringify(lexicon)),
      ),
    )
    execFileSync(
      process.execPath,
      [lexEntry, 'build', '--lexicons', inputDir, '--out', lexiconsDir, '--clear', '--index-file'],
      { stdio: ['ignore', 'ignore', 'inherit'] },
    )
  } finally {
    await rm(inputDir, { recursive: true, force: true })
  }
  await normalizeOutput(lexiconsDir)
  await writeIndex(srcDir)
  return lexicons.length
}

/** @param {string} dir @returns {Promise<Map<string, string>>} every file under dir */
async function readGenerated(dir) {
  const files = await listFiles(dir)
  const contents = await Promise.all(files.map((file) => readFile(path.join(dir, file), 'utf8')))
  return new Map(files.map((file, index) => [file, contents[index] ?? '']))
}

async function main() {
  const check = process.argv.includes('--check')
  const srcDir = path.join(packageRoot, 'src')

  if (!check) {
    const count = await generate(srcDir)
    console.log(`Generated @hypercerts-org/cgs from ${count} CGS Lexicons.`)
    return
  }

  const outDir = await mkdtemp(path.join(tmpdir(), 'hypercerts-cgs-src-'))
  try {
    await mkdir(path.join(outDir, 'src'))
    await generate(path.join(outDir, 'src'))
    const expected = await readGenerated(path.join(outDir, 'src'))
    const actual = await readGenerated(srcDir)
    const stale = [...new Set([...expected.keys(), ...actual.keys()])]
      .filter((file) => expected.get(file) !== actual.get(file))
      .sort(byCodeUnit)
    if (stale.length > 0) {
      const list = stale.map((file) => `  ${file}`).join('\n')
      console.error(`Generated sources are stale. Run \`pnpm client:generate\`.\n${list}`)
      process.exitCode = 1
      return
    }
    console.log('Generated sources are up to date.')
  } finally {
    await rm(outDir, { recursive: true, force: true })
  }
}

await main()
